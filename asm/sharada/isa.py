"""
Sharada ISA: the single source of truth.

The assembler, the golden-model ISS and the RTL package (src/sh_pkg.sv,
generated by `python3 -m sharada.gen_pkg`) all read their encodings from
here. Change a number here, regenerate, and everything moves together.

Instruction word, 32 bits:

    31    26 25 23 22 20 19 17  16  15             0
    +-------+-----+-----+-----+---+----------------+
    |  op   | rd  | rs  | rt  | i |     imm16      |
    +-------+-----+-----+-----+---+----------------+

    B operand = i ? imm16 : R[rt]
    Branch target = imm16[IMEM_AW-1:0] (absolute word address)
    Bit-test index (BBS/BBC) = imm16[15:12]
"""

XLEN = 16            # datapath width
NREGS = 8            # r0 reads as zero
NTHREADS = 4
IMEM_AW = 9          # 512 words
IMEM_WORDS = 1 << IMEM_AW
NLANES = 4
CHAN_DEPTH = 4

# --------------------------------------------------------------------------
# Opcodes. Grouped by the top bits so the decoder stays shallow.
# --------------------------------------------------------------------------
OPCODES = {
    # ALU: rd = rs <op> B
    "NOP":  0x00,
    "ADD":  0x01,
    "SUB":  0x02,
    "AND":  0x03,
    "OR":   0x04,
    "XOR":  0x05,
    "SHL":  0x06,   # rd = rs << B[4:0] (0 if >= 16)
    "SHR":  0x07,   # logical
    "PAR":  0x08,   # rd = ^(rs & B)
    "SLTU": 0x09,   # rd = rs < B (unsigned)
    # Control flow
    "JMP":  0x10,
    "BEQ":  0x11,   # if R[rs] == R[rt]
    "BNE":  0x12,
    "BLTU": 0x13,
    "BGEU": 0x14,
    "BBS":  0x15,   # if R[rs][bit] == 1
    "BBC":  0x16,
    "DJNZ": 0x17,   # rd = R[rs] - 1; branch if result != 0 (assembler sets rs = rd)
    "JAL":  0x18,   # rd = pc + 1; pc = target
    "JR":   0x19,   # pc = R[rs]
    # IO and time
    "IOR":  0x20,   # rd = io[imm[7:0]]          (may block)
    "IOW":  0x21,   # io[imm[7:0]] = R[rs]       (may block)
    "WAIT": 0x22,   # block until condition, see WAIT_* below
    "DLY":  0x23,   # sleep B thread-slots
    "HALT": 0x24,
}

ALU_OPS = {"ADD", "SUB", "AND", "OR", "XOR", "SHL", "SHR", "PAR", "SLTU"}
REG_BRANCHES = {"BEQ", "BNE", "BLTU", "BGEU"}
BIT_BRANCHES = {"BBS", "BBC"}

# WAIT immediate:
#   imm[15] = 0 : event wait.  imm[9:8] = lane, imm[7:0] = event mask.
#                 Completes when (lane.events & mask) != 0, and clears the
#                 sticky events it matched (so a WAIT consumes its event).
#   imm[15] = 1 : pin wait.    imm[4:0] = pin, imm[5] = level.
WAIT_PIN_FLAG = 1 << 15

# --------------------------------------------------------------------------
# IO space (8-bit addresses)
# --------------------------------------------------------------------------
IO = {
    "CH_HOST":      0x00,  # R: pop host->core channel.  W: push core->host channel.
    "CH_A":         0x01,  # R: pop, W: push.  Inter-thread channel.
    "CH_B":         0x02,
    "GPIO_OUT":     0x04,  # [7:0] uio, [15:10] uo[7:2]
    "GPIO_OUT_SET": 0x05,
    "GPIO_OUT_CLR": 0x06,
    "GPIO_OE":      0x07,  # [7:0] uio output enables
    "GPIO_OE_SET":  0x08,
    "GPIO_OE_CLR":  0x09,
    "PINS":         0x0A,  # R: {ui_in, uio_in} synchronised
    "TID":          0x0B,  # R: own thread id
    "TIMER":        0x0C,  # R: free-running clock-cycle counter, low 16 bits
    "SPAWN":        0x0D,  # W: [10:9] tid, [8:0] pc.  Starts that thread.
    "STOP":         0x0E,  # W: [3:0] mask of threads to stop
}

LANE_BASE = 0x10
LANE_STRIDE = 0x10
LANE_REGS = {
    "DATA":   0x0,  # R: pop RX word (blocks). W: push TX word (blocks), tagged with TXTAG.
    "STATUS": 0x1,  # R: events.  W: write-1-to-clear sticky events.
    "CTRL":   0x2,
    "DIV":    0x3,  # bit period in clocks, minus 1
    "SAMPLE": 0x4,  # phase at which RX samples
    "SJW":    0x5,  # resync jump width, in clocks
    "PINSEL": 0x6,  # [4:0] tx pin, [9:5] rx pin, [14:10] clk pin
    "RXCFG":  0x7,  # [3:0] rx bits-1, [7:4] destuff N (0 = off), [8] rx crc enable
    "TXTAG":  0x8,  # latched with every DATA write: [3:0] bits-1, [4] stuff, [5] crc, [6] send crc
    "TXCFG":  0x9,  # [3:0] stuff N (0 = off)
    "CRC":    0xA,  # R/W: CRC register
    "POLY":   0xB,  # CRC polynomial (without the implicit top bit)
    "CRCW":   0xC,  # CRC width - 1
    "EDGE":   0xD,  # phase of SCK's middle edge (controller mode)
}

CTRL_BITS = {
    "EN":        0,   # lane enable (timer runs)
    "TXEN":      1,   # drive the tx pin
    "OD":        2,   # open drain: only ever drive 0
    "IDLE":      3,   # level driven when tx is idle
    "MSB":       4,   # MSB first
    "CLKEN":     5,   # drive the clk pin (synchronous controller)
    "CPOL":      6,
    "CPHA":      7,
    "RXMODE":    8,   # 2 bits: 0 off, 1 hunt, 2 stream, 3 sync
    "RESYNC":    10,  # falling RX edges pull the bit timer, bounded by SJW
    "ABORT":     11,  # arbitration loss stops TX until MISMATCH is cleared
    "CLKOD":     12,  # clk pin open drain, with clock stretching
    "LOOP":      13,  # internal loopback tx -> rx
}
RXMODE = {"OFF": 0, "HUNT": 1, "STREAM": 2, "SYNC": 3}

EVENTS = {
    "TXE":      0,  # tx buffer has space            (level)
    "TXDONE":   1,  # tx buffer and shifter empty     (level)
    "RXF":      2,  # rx word available               (level)
    "MISMATCH": 3,  # driven bit != sampled bit       (sticky)
    "STUFFERR": 4,  # stuff rule violated on rx       (sticky)
    "EDGE":     5,  # falling edge on rx              (sticky)
    "TICK":     6,  # bit boundary                    (sticky)
    "RXOVF":    7,  # rx word overwritten unread      (sticky)
}
STICKY_MASK = 0xF8

# Pin numbering used by PINSEL, WAIT and the docs.
#   0..7   uio[0..7]   bidirectional
#   8..15  ui_in[0..7] input only (ui[2:0] carry the host port)
#   16..23 uo_out[0..7] output only (uo[1:0] carry the host port)
PIN_UIO = 0
PIN_UI = 8
PIN_UO = 16

# --------------------------------------------------------------------------
# Host port (SPI target on ui[0]=SCK, ui[1]=CS_n, ui[2]=MOSI, uo[0]=MISO,
# uo[1]=IRQ: core->host channel not empty). Mode 0, MSB first.
# --------------------------------------------------------------------------
HOST_CMDS = {
    "WRITE_IMEM": 0x01,  # addr_hi addr_lo {b3 b2 b1 b0}*   (auto-increment)
    "SPAWN":      0x02,  # tid pc_hi pc_lo
    "STOP":       0x03,  # mask
    "PUSH":       0x04,  # hi lo                          -> host->core channel
    "POP":        0x05,  # returns valid hi lo            <- core->host channel
    "STATUS":     0x06,  # returns status byte
    "LOCKSTEP":   0x07,  # mask: bit p pairs thread p (master) with p+2; clears faults
}


def lane_reg(lane: int, name: str) -> int:
    return LANE_BASE + LANE_STRIDE * lane + LANE_REGS[name]


def symbols() -> dict:
    """Every name the assembler knows, flattened."""
    s = {}
    s.update(IO)
    for k in range(NLANES):
        s[f"LANE{k}"] = k
        for name, off in LANE_REGS.items():
            s[f"L{k}_{name}"] = lane_reg(k, name)
    for name, bit in CTRL_BITS.items():
        s[f"C_{name}"] = 1 << bit
    for name, val in RXMODE.items():
        s[f"RX_{name}"] = val << CTRL_BITS["RXMODE"]
    for name, bit in EVENTS.items():
        s[f"E_{name}"] = 1 << bit
    for i in range(8):
        s[f"P_UIO{i}"] = PIN_UIO + i
        s[f"P_UI{i}"] = PIN_UI + i
        s[f"P_UO{i}"] = PIN_UO + i
    return s


def encode(op: str, rd=0, rs=0, rt=0, i=0, imm=0) -> int:
    assert 0 <= rd < NREGS and 0 <= rs < NREGS and 0 <= rt < NREGS
    return ((OPCODES[op] << 26) | (rd << 23) | (rs << 20) | (rt << 17)
            | ((i & 1) << 16) | (imm & 0xFFFF))


def decode(word: int) -> dict:
    op = (word >> 26) & 0x3F
    names = {v: k for k, v in OPCODES.items()}
    return {
        "op": names.get(op, f"ILLEGAL_{op:#x}"),
        "rd": (word >> 23) & 7,
        "rs": (word >> 20) & 7,
        "rt": (word >> 17) & 7,
        "i": (word >> 16) & 1,
        "imm": word & 0xFFFF,
    }
