"""Generate src/sh_pkg.sv from isa.py.  Run from asm/:  python3 -m sharada.gen_pkg"""

import pathlib
import sys

from . import isa

OUT = pathlib.Path(__file__).resolve().parents[2] / "src" / "sh_pkg.sv"


def render() -> str:
    L = []
    w = L.append
    w("// GENERATED by asm/sharada/gen_pkg.py from asm/sharada/isa.py. Do not edit.")
    w("// SPDX-License-Identifier: Apache-2.0")
    w("`default_nettype none")
    w("")
    w("package sh_pkg;")
    w("")
    w(f"  localparam int XLEN       = {isa.XLEN};")
    w(f"  localparam int NREGS      = {isa.NREGS};")
    w(f"  localparam int NTHREADS   = {isa.NTHREADS};")
    w(f"  localparam int IMEM_AW    = {isa.IMEM_AW};")
    w(f"  localparam int NLANES     = {isa.NLANES};")
    w(f"  localparam logic [NLANES-1:0] LANES_FULL = {isa.NLANES}'b{isa.LANES_FULL:0{isa.NLANES}b};")
    w(f"  localparam int CHAN_DEPTH = {isa.CHAN_DEPTH};")
    w(f"  localparam int HOST_DEPTH = {isa.HOST_DEPTH};")
    w("")
    w("  // Opcodes")
    for name, val in isa.OPCODES.items():
        w(f"  localparam logic [5:0] OP_{name:<5} = 6'h{val:02x};")
    w("")
    w("  // IO space")
    for name, val in isa.IO.items():
        w(f"  localparam logic [7:0] IO_{name:<12} = 8'h{val:02x};")
    w(f"  localparam logic [7:0] IO_LANE_BASE    = 8'h{isa.LANE_BASE:02x};")
    w(f"  localparam int LANE_SHIFT = {isa.LANE_SHIFT};   // a lane's window is 2**LANE_SHIFT registers")
    w("")
    w("  // Lane register offsets")
    for name, val in isa.LANE_REGS.items():
        w(f"  localparam logic [{isa.LANE_SHIFT-1}:0] LR_{name:<6} = {isa.LANE_SHIFT}'h{val:x};")
    w("")
    w("  // CTRL bit positions")
    for name, val in isa.CTRL_BITS.items():
        w(f"  localparam int CB_{name:<6} = {val};")
    w("")
    w("  // TXTAG bit positions and start conditions")
    for name, val in isa.TXTAG_BITS.items():
        w(f"  localparam int TT_{name:<7} = {val};")
    w(f"  localparam int TT_START   = {isa.TX_START_SHIFT};")
    for name, val in isa.TX_START.items():
        w(f"  localparam logic [1:0] TS_{name:<7} = 2'd{val};")
    w("")
    w("  // TXCFG / RXCFG fields and line codes")
    for name, val in isa.TXCFG_BITS.items():
        w(f"  localparam int TC_{name:<4} = {val};")
    w(f"  localparam int TC_CODE = {isa.TXCFG_CODE_SHIFT};")
    for name, val in isa.RXCFG_BITS.items():
        w(f"  localparam int RC_{name:<4} = {val};")
    w(f"  localparam int RC_CODE = {isa.RXCFG_CODE_SHIFT};")
    for name, val in isa.LINE_CODES.items():
        w(f"  localparam logic [1:0] LC_{name:<5} = 2'd{val};")
    w(f"  localparam int TC_FIX  = {isa.TXCFG_FIX_SHIFT};")
    w("")
    w("  // LFSR modes and LCFG bits")
    for name, val in isa.LFSR_MODES.items():
        w(f"  localparam logic [1:0] LF_{name:<5} = 2'd{val};")
    for name, val in isa.LCFG_BITS.items():
        w(f"  localparam int LB_{name:<6} = {val};")
    w("")
    w("  // LCTL2 bits, idle modes, RXCFG2 K")
    for name, val in isa.LCTL2_BITS.items():
        w(f"  localparam int L2_{name:<8} = {val};")
    w(f"  localparam int L2_IDLE = {isa.LCTL2_IDLE_SHIFT};")
    for name, val in isa.LCTL2_IDLE.items():
        w(f"  localparam logic [1:0] IM_{name:<7} = 2'd{val};")
    w(f"  localparam int RC2_K = {isa.RXCFG2_K_SHIFT};")
    w("")
    w("  // STATUS bit positions above the events")
    for name, val in isa.STATUS_BITS.items():
        w(f"  localparam int ST_{name:<4} = {val};")
    w("")
    w("  // Event bit positions")
    for name, val in isa.EVENTS.items():
        w(f"  localparam int EV_{name:<8} = {val};")
    w(f"  localparam int NEVENTS = {isa.NEVENTS};")
    w(f"  localparam logic [{isa.NEVENTS-1}:0] EV_STICKY = {isa.NEVENTS}'h{isa.STICKY_MASK:03x};")
    w(f"  localparam int WAIT_EV_HI = {isa.WAIT_EV_HI_SHIFT};")
    w("")
    w("  // Host port commands")
    for name, val in isa.HOST_CMDS.items():
        w(f"  localparam logic [7:0] HC_{name:<10} = 8'h{val:02x};")
    w("")
    w("endpackage")
    w("")
    return "\n".join(L)


def main():
    text = render()
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            sys.exit(f"{OUT} is stale; run python3 -m sharada.gen_pkg")
        return
    OUT.write_text(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
